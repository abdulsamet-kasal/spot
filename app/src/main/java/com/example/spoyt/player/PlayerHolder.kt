/** Queue repeat behaviour, owned by the app (ExoPlayer only ever plays one item). */
enum class RepeatMode { OFF, ALL, ONE }

/**
 * Holds the ExoPlayer instance and the playback state shared across the app.
 *
 * Responsibilities:
 *   - Own a single ExoPlayer (single-activity app, background playback).
 *   - Expose current track, queue, index, and play/pause state as StateFlows.
 *   - Provide queue operations (play a track, play a list, next, previous, reorder).
 *
 * Stream URLs are resolved lazily: when a track becomes current and no source is known yet,
 * [onSourceMissing] is invoked so the controller can resolve it and call [reloadCurrent].
 * That keeps "next" instant instead of pre-resolving the whole queue over the network.
 *
 * Initialized once from [MusicPlaybackService] (which owns the Android Context).
 */
object PlayerHolder {

    /** Browser-like User-Agent; YouTube's CDN rejects some non-browser clients. */
    const val HTTP_USER_AGENT =
        "Mozilla/5.0 (Linux; Android 13; Pixel 7 Build/TD1A.220804.031; wv) " +
            "AppleWebKit/537.36 (KHTML, like Gecko) Version/4.0 Chrome/120.0.6099.144 " +
            "Mobile Safari/537.36"

    /**
     * User-Agent of the YouTube Android app. googlevideo URLs carrying `c=ANDROID` were
     * generated for that client, and the CDN serves truncated (~1 minute) responses to
     * requests whose User-Agent does not match the client that produced the URL.
     */
    const val ANDROID_STREAM_USER_AGENT =
        "com.google.android.youtube/19.44.38 (Linux; U; Android 11) gzip"

    /** Same idea for streams generated by the iOS player client (`c=IOS`). */
    private const val IOS_STREAM_USER_AGENT =
        "com.google.ios.youtube/19.44.38 (iPhone14,3; U; CPU iOS 17_1_2 like Mac OS X)"

    /**
     * Picks the playback User-Agent for [url]: the client that produced a googlevideo URL
     * is encoded in its `c=` query parameter, and the CDN only serves complete responses
     * when the request's User-Agent matches that client.
     */
    fun userAgentFor(url: String): String = when {
        url.contains("c=ANDROID", ignoreCase = true) -> ANDROID_STREAM_USER_AGENT
        url.contains("c=IOS", ignoreCase = true) -> IOS_STREAM_USER_AGENT
        else -> HTTP_USER_AGENT
    }

    private var exoPlayer: ExoPlayer? = null

    /** videoId -> resolved stream, used to build the playable media item. */
    private val streamSources =
        java.util.concurrent.ConcurrentHashMap<String, ResolvedStream>()

    private val _currentTrack = MutableStateFlow<TrackEntity?>(null)
    private val _queue = MutableStateFlow<List<TrackEntity>>(emptyList())
    private val _currentIndex = MutableStateFlow(0)
    private val _isPlaying = MutableStateFlow(false)
    private val _isBuffering = MutableStateFlow(false)
    private val _repeatMode = MutableStateFlow(RepeatMode.OFF)
    private val _playbackSpeed = MutableStateFlow(1.0f)

    /** Read-only exposures for the UI layer. */
    val currentTrackState: StateFlow<TrackEntity?> = _currentTrack.asStateFlow()
    val queueState: StateFlow<List<TrackEntity>> = _queue.asStateFlow()
    val currentIndexState: StateFlow<Int> = _currentIndex.asStateFlow()
    val isPlayingState: StateFlow<Boolean> = _isPlaying.asStateFlow()
    val isBufferingState: StateFlow<Boolean> = _isBuffering.asStateFlow()
    val repeatModeState: StateFlow<RepeatMode> = _repeatMode.asStateFlow()
    val playbackSpeedState: StateFlow<Float> = _playbackSpeed.asStateFlow()

    /** Set by [PlaybackController]: the current track has no playable source yet. */
    var onSourceMissing: ((TrackEntity) -> Unit)? = null

    /**
     * ExoPlayer is bound to the thread that created it (the main thread). Background
     * coroutines (stream resolution, retries) must never touch it directly, otherwise the
     * process dies with "Player is accessed on the wrong thread". Every call that mutates
     * the player therefore hops to the main looper first.
     */
    private val mainHandler by lazy { Handler(Looper.getMainLooper()) }

    private fun runOnMain(block: () -> Unit) {
        if (Looper.myLooper() == Looper.getMainLooper()) block() else mainHandler.post(block)
    }


    /** Set by [PlaybackController]: playback failed (expired URL / CDN error), retry once. */
    var onPlaybackFailed: ((TrackEntity) -> Unit)? = null

    /** videoIds with an in-flight resolution request, so we never resolve the same track twice. */
    private val resolving: MutableSet<String> =
        java.util.Collections.synchronizedSet(mutableSetOf())

    /** videoIds that already burned their single automatic retry. */
    private val retried: MutableSet<String> =
        java.util.Collections.synchronizedSet(mutableSetOf())

    /**
     * Position (ms) to resume from after a mid-stream failure. Set by the error handler,
     * consumed by [attachAndPlay]: re-resolving the URL must not restart the song from
     * the beginning when the CDN dropped us halfway through.
     */
    private var resumePositionMs = 0L

    /** Current playback position in milliseconds (read synchronously for the seek bar). */
    val positionMs: Long
        get() = exoPlayer?.currentPosition ?: 0L

    /** Total duration in milliseconds, or 0 when unknown. */
    val durationMs: Long
        get() = exoPlayer?.duration?.takeIf { it > 0 } ?: 0L

    fun init(context: Context) {
        if (exoPlayer != null) return
        // Creating an ExoPlayer binds it to the current thread's looper, so it must happen on
        // the main thread even when the request comes from a background coroutine.
        if (Looper.myLooper() != Looper.getMainLooper()) {
            mainHandler.post { init(context) }
            return
        }
        try {
            val mediaSourceFactory = DefaultMediaSourceFactory(UaSwitchingDataSource.Factory())

            // A generous audio buffer: mobile networks stall briefly, and a bigger buffer
            // rides those out instead of stopping playback.
            val loadControl = androidx.media3.exoplayer.DefaultLoadControl.Builder()
                .setBufferDurationsMs(
                    /* minBufferMs = */ 30_000,
                    /* maxBufferMs = */ 120_000,
                    /* bufferForPlaybackMs = */ 2_500,
                    /* bufferForPlaybackAfterRebufferMs = */ 5_000
                )
                .setPrioritizeTimeOverSizeThresholds(true)
                .build()

            val p = ExoPlayer.Builder(context, mediaSourceFactory)
                .setLoadControl(loadControl)
                .build()

            // Music audio focus: pause when another app takes audio, duck on interruptions.
            p.setAudioAttributes(
                AudioAttributes.Builder()
                    .setContentType(C.AUDIO_CONTENT_TYPE_MUSIC)
                    .setUsage(C.USAGE_MEDIA)
                    .build(),
                /* handleAudioFocus = */ true
            )

            // PlaybackParameters survive per-item swaps but not a player rebuild (the media
            // service may have released the previous engine), so re-apply the saved speed.
            val speed = _playbackSpeed.value
            if (speed != 1.0f) {
                runCatching { p.playbackParameters = androidx.media3.common.PlaybackParameters(speed) }
            }

            p.addListener(object : Player.Listener {
                override fun onIsPlayingChanged(isPlaying: Boolean) {
                    _isPlaying.value = isPlaying
                }

                override fun onPlaybackStateChanged(playbackState: Int) {
                    _isBuffering.value = playbackState == Player.STATE_BUFFERING
                    when (playbackState) {
                        Player.STATE_READY -> {
                            // The source works: clear the retry bookkeeping for this track.
                            _currentTrack.value?.let { retried.remove(it.videoId) }
                        }

                        Player.STATE_ENDED -> {
                            // YouTube sometimes serves truncated audio: the stream "ends"
                            // while the real track still has minutes left. Detect that and
                            // restart with a fresh URL instead of skipping to the next song.
                            if (endedPrematurely()) recoverFromPrematureEnd() else playNext()
                        }
                    }
                }

                override fun onPlayerError(error: PlaybackException) {
                    _isPlaying.value = false
                    _isBuffering.value = false
                    val p = exoPlayer
                    val track = _currentTrack.value ?: return
                    val duration = p?.duration?.takeIf { it > 0 } ?: 0L
                    val position = p?.currentPosition ?: 0L
                    // An error at the very end of the track is effectively "finished":
                    // advance instead of wasting a retry on the last second.
                    if (duration > 0 && position >= duration - 1_500) {
                        playNext()
                        return
                    }
                    // Resume from where the CDN dropped us (anything past the intro);
                    // restart from zero when the failure came immediately.
                    resumePositionMs = if (position > 3_000) position else 0L
                    // Expired googlevideo URLs and transient CDN errors are worth one retry:
                    // the controller re-resolves the stream and calls reloadCurrent().
                    val canRetry = onPlaybackFailed != null && retried.add(track.videoId)
                    if (canRetry) {
                        invalidateStream(track.videoId)
                        onPlaybackFailed?.invoke(track)
                    } else {
                        PlaybackEvents.post("Bu şarkı şu anda oynatılamıyor.")
                    }
                }
            })
            exoPlayer = p
        } catch (t: Throwable) {
            // A failed player build must not crash the app; the UI reports it when it tries
            // to play and finds no engine.
            exoPlayer = null
        }
    }

    val isInitialized: Boolean
        get() = exoPlayer != null

    /**
     * The live [ExoPlayer] instance, exposed so [MusicPlaybackService] can wrap it in a
     * [androidx.media3.session.MediaSession].
     */
    val engine: ExoPlayer
        get() = exoPlayer ?: error("PlayerHolder not initialized. Call init(Context) first.")

    // ---------------------------------------------------------------- sources

    /** Register a resolved stream for a track so it can be played. */
    fun setStreamSource(videoId: String, stream: ResolvedStream) {
        streamSources[videoId] = stream
    }

    /** Look up a still-valid resolved stream for [videoId], if any. */
    fun streamFor(videoId: String): ResolvedStream? {
        val stream = streamSources[videoId] ?: return null
        if (stream.isExpired()) {
            streamSources.remove(videoId)
            return null
        }
        return stream
    }

    /** Drops a cached stream so the next attempt resolves a fresh URL. */
    fun invalidateStream(videoId: String) {
        streamSources.remove(videoId)
    }

    /** Called by the controller when a resolution attempt finished (success or failure). */
    fun onResolutionFinished(videoId: String) {
        resolving.remove(videoId)
        // A failed resolution should not block a later manual retry.
        if (resolveUri(videoId) == null) retried.remove(videoId)
    }

    val currentHasSource: Boolean
        get() = _currentTrack.value?.let { resolveUri(it.videoId) != null } ?: false

    // ---------------------------------------------------------------- queue

    /** Set the queue WITHOUT starting playback (the controller resolves, then calls [start]). */
    fun setQueueSilently(tracks: List<TrackEntity>, startIndex: Int = 0) {
        if (tracks.isEmpty()) return
        val safeIndex = startIndex.coerceIn(0, tracks.size - 1)
        _queue.value = tracks.toList()
        _currentIndex.value = safeIndex
        _currentTrack.value = tracks[safeIndex]
    }

    /** Set the queue and start playing from the given index. */
    fun setQueue(tracks: List<TrackEntity>, startIndex: Int = 0) {
        setQueueSilently(tracks, startIndex)
        start()
    }

    /** Append tracks to the queue. */
    fun addToQueue(tracks: List<TrackEntity>) {
        _queue.value = _queue.value + tracks
    }

    /** Play a single track (replaces the queue with just this track). */
    fun play(track: TrackEntity) {
        setQueue(listOf(track), 0)
    }

    /** Play the track at [index] in the current queue. */
    fun playIndex(index: Int) {
        val q = _queue.value
        if (q.isEmpty() || index !in q.indices) return
        // Selecting a track (manually or via next/previous) starts a new attempt session:
        // its retry budget must not inherit a previous failure.
        retried.remove(q[index].videoId)
        _currentIndex.value = index
        _currentTrack.value = q[index]
        start()
    }

    fun playNext() {
        runOnMain {
            val q = _queue.value
            if (q.isEmpty()) return@runOnMain

            // Repeat-one replays the current track without advancing.
            if (_repeatMode.value == RepeatMode.ONE) {
                exoPlayer?.seekTo(0)
                playIndex(_currentIndex.value)
                return@runOnMain
            }

            val next = _currentIndex.value + 1
            if (next > q.lastIndex) {
                if (_repeatMode.value == RepeatMode.ALL) {
                    // Wrap around to the beginning of the queue.
                    playIndex(0)
                    return@runOnMain
                }
                // End of queue: stop instead of silently restarting the last track.
                exoPlayer?.let {
                    it.pause()
                    it.seekTo(0)
                }
                _isPlaying.value = false
                return@runOnMain
            }
            playIndex(next)
        }
    }

    fun playPrevious() {
        runOnMain {
            val q = _queue.value
            if (q.isEmpty()) return@runOnMain
            // Standard behaviour: restart the song unless we are already at the beginning.
            val p = exoPlayer
            if (p != null && p.currentPosition > 3_000) {
                p.seekTo(0)
                return@runOnMain
            }
            playIndex((_currentIndex.value - 1).coerceAtLeast(0))
        }
    }

    fun playPause() {
        runOnMain {
            val p = exoPlayer ?: return@runOnMain
            if (p.isPlaying) {
                p.pause()
            } else if (p.playbackState == Player.STATE_IDLE) {
                // The engine is idle (fresh player, or a previous stream failed). A manual
                // play must not reuse the cached URL that just failed: give the track a
                // fresh retry budget and force a new resolution.
                _currentTrack.value?.let { track ->
                    retried.remove(track.videoId)
                    invalidateStream(track.videoId)
                }
                start()
            } else {
                p.play()
            }
        }
    }

    /** Pause without toggling (used by the sleep timer). */
    fun pause() {
        runOnMain { runCatching { exoPlayer?.pause() } }
    }

    /** Cycles OFF -> ALL -> ONE -> OFF. */
    fun cycleRepeatMode() {
        _repeatMode.value = when (_repeatMode.value) {
            RepeatMode.OFF -> RepeatMode.ALL
            RepeatMode.ALL -> RepeatMode.ONE
            RepeatMode.ONE -> RepeatMode.OFF
        }
    }

    /** Sets the playback speed (0.5x..2x range enforced by the UI). */
    fun setSpeed(speed: Float) {
        val clamped = speed.coerceIn(0.5f, 2.5f)
        _playbackSpeed.value = clamped
        runOnMain {
            runCatching {
                exoPlayer?.playbackParameters =
                    androidx.media3.common.PlaybackParameters(clamped)
            }
        }
    }

    /** Removes an upcoming track from the queue (the playing row itself is not touchable). */
    fun removeFromQueue(index: Int) {
        val q = _queue.value.toMutableList()
        if (index !in q.indices) return
        q.removeAt(index)
        _queue.value = q
        if (index < _currentIndex.value) {
            _currentIndex.value = (_currentIndex.value - 1).coerceAtLeast(0)
        }
    }

    /** Moves a queue row (drag-free reorder used by the queue sheet). */
    fun moveInQueue(from: Int, to: Int) {
        if (from == to) return
        val q = _queue.value.toMutableList()
        if (from !in q.indices || to !in q.indices) return
        val item = q.removeAt(from)
        q.add(to, item)
        _queue.value = q
        // Keep the playing row pointing at the same track after the shift.
        val cur = _currentIndex.value
        _currentIndex.value = when {
            cur == from -> to
            from < cur && to >= cur -> cur - 1
            from > cur && to <= cur -> cur + 1
            else -> cur
        }
    }

    fun seekTo(positionMs: Long) {
        runOnMain { exoPlayer?.seekTo(positionMs) }
    }

    /**
     * Immediate feedback when the user picks another track.
     *
     * Resolving a fresh stream URL takes a moment; without this the outgoing song keeps
     * playing in the meantime, which feels like the app "changed the title but not the song".
     * Pausing here (and showing the buffering spinner) makes the switch feel instant.
     */
    fun beginLoading() {
        runOnMain {
            _isBuffering.value = true
            _isPlaying.value = false
            runCatching { exoPlayer?.pause() }
        }
    }

    /** Drops the loading spinner when the requested track turned out to be unplayable. */
    fun clearLoading() {
        runOnMain { _isBuffering.value = false }
    }

    /**
     * True when the player just reached STATE_ENDED while the known track duration says
     * there should still be a substantial part left. That means the CDN served a truncated
     * (or range-limited) stream, not that the song finished.
     */
    private fun endedPrematurely(): Boolean {
        val p = exoPlayer ?: return false
        val track = _currentTrack.value ?: return false
        val expectedMs = track.durationSeconds * 1000
        if (expectedMs <= 0) return false
        val servedMs = p.duration.takeIf { it > 0 } ?: return false
        return servedMs < expectedMs * 9 / 10
    }

    /**
     * Recovers from a truncated stream: drop the cached URL, re-resolve a fresh one and
     * replay from the start (a partial body carries no usable position mapping). After the
     * retry budget is exhausted the end is treated as a normal end so the queue keeps going.
     */
    private fun recoverFromPrematureEnd() {
        val track = _currentTrack.value ?: return
        val canRetry = onPlaybackFailed != null && retried.add(track.videoId)
        if (canRetry) {
            resumePositionMs = 0L
            invalidateStream(track.videoId)
            onPlaybackFailed?.invoke(track)
        } else {
            PlaybackEvents.post("Şarkı tam yüklenemedi, sıradakine geçiliyor.")
            playNext()
        }
    }

    /** Start (or restart) the currently selected track using an already-known source. */
    fun start() {
        val track = _currentTrack.value ?: return
        if (resolveUri(track.videoId) == null) {
            // Not resolved yet: ask the controller to resolve it exactly once, the controller
            // then calls reloadCurrent() when it has a URL (or posts an error message).
            if (resolving.add(track.videoId)) onSourceMissing?.invoke(track)
            _isPlaying.value = false
            return
        }
        attachAndPlay(track)
    }

    /** Re-attach the current track to the player (used after a source was resolved/refreshed). */
    fun reloadCurrent() {
        val track = _currentTrack.value ?: return
        if (resolveUri(track.videoId) == null) {
            _isPlaying.value = false
            _isBuffering.value = false
            return
        }
        attachAndPlay(track)
    }

    private fun attachAndPlay(track: TrackEntity) {
        if (Looper.myLooper() != Looper.getMainLooper()) {
            mainHandler.post { attachAndPlay(track) }
            return
        }
        val uri = resolveUri(track.videoId) ?: return
        // Defensive: if the engine is not available yet, say so instead of throwing.
        val p = exoPlayer ?: run {
            _isBuffering.value = false
            _isPlaying.value = false
            PlaybackEvents.post("Oynatıcı hazır değil. Tekrar deneyin.")
            return
        }
        val stream = streamSources[track.videoId]
        val mediaItem = MediaItem.Builder()
            .setUri(uri)
            .setMimeType(stream?.mimeType)
            .setMediaMetadata(
                MediaMetadata.Builder()
                    .setTitle(track.title)
                    .setArtist(track.artist)
                    .setArtworkUri(track.thumbnailUrl?.let { Uri.parse(it) })
                    .build()
            )
            .build()

        try {
            // Resume from the saved position after a mid-stream failure; 0 on a normal start.
            val startPosition = resumePositionMs.coerceAtLeast(0L)
            resumePositionMs = 0L
            p.setMediaItem(mediaItem, startPosition)
            p.prepare()
            p.play()
            _isBuffering.value = true
        } catch (t: Throwable) {
            // Never let a player-layer failure kill the process; report it in the UI instead.
            _isBuffering.value = false
            _isPlaying.value = false
            PlaybackEvents.post("Şarkı başlatılamadı. Lütfen tekrar deneyin.")
        }
    }

    /** Prefer the local download file if available; otherwise use the resolved stream URL. */
    private fun resolveUri(videoId: String): Uri? {
        val downloadPath = DownloadPaths.pathFor(videoId)
        if (downloadPath.isNotEmpty()) {
            val file = java.io.File(downloadPath)
            if (file.exists() && file.length() > 0) return Uri.fromFile(file)
            DownloadPaths.remove(videoId)
        }
        val stream = streamFor(videoId) ?: return null
        return Uri.parse(stream.url)
    }

    fun release() {
        runOnMain {
            exoPlayer?.release()
            exoPlayer = null
            streamSources.clear()
            resolving.clear()
            retried.clear()
        }
    }
}

/**
 * In-memory record of downloaded file paths keyed by videoId.
 * Populated when a download finishes and re-hydrated from Room on every playback attempt.
 */
object DownloadPaths {
    private val paths = java.util.concurrent.ConcurrentHashMap<String, String>()

    fun pathFor(videoId: String): String = paths[videoId] ?: ""

    fun set(videoId: String, path: String) {
        paths[videoId] = path
    }

    fun remove(videoId: String) {
        paths.remove(videoId)
    }
}

/**
 * [DataSource] that switches the HTTP User-Agent per request based on the media URL.
 *
 * googlevideo URLs are client-specific: the CDN that serves them expects the request to
 * carry the User-Agent of the YouTube client encoded in the URL's `c=` parameter, and
 * serves truncated (~1 minute) responses to mismatched clients. Local download files
 * (file:// URIs) are served by a plain [FileDataSource].
 *
 * A fresh delegate is built per `open()` so concurrent loads never share mutable factory
 * state; transfer listeners registered between opens are applied before every open.
 */
private class UaSwitchingDataSource : DataSource {

    private val listeners = mutableListOf<TransferListener>()
    private var delegate: DataSource? = null

    override fun addTransferListener(transferListener: TransferListener) {
        listeners.add(transferListener)
    }

    override fun open(dataSpec: DataSpec): Long {
        val d: DataSource = when (dataSpec.uri.scheme?.lowercase()) {
            "http", "https" -> DefaultHttpDataSource.Factory()
                .setUserAgent(PlayerHolder.userAgentFor(dataSpec.uri.toString()))
                .setConnectTimeoutMs(15_000)
                .setReadTimeoutMs(30_000)
                .setAllowCrossProtocolRedirects(true)
                .createDataSource()
            else -> FileDataSource()
        }
        listeners.forEach { listener -> runCatching { d.addTransferListener(listener) } }
        delegate = d
        return d.open(dataSpec)
    }

    override fun read(target: ByteArray, offset: Int, length: Int): Int =
        delegate?.read(target, offset, length) ?: C.RESULT_END_OF_INPUT

    override fun getUri(): Uri? = delegate?.uri

    override fun getResponseHeaders(): Map<String, MutableList<String>> =
        delegate?.responseHeaders ?: emptyMap()

    override fun close() {
        try {
            delegate?.close()
        } finally {
            delegate = null
        }
    }

    /** Factory used by [DefaultMediaSourceFactory]. */
    class Factory : DataSource.Factory {
        override fun createDataSource(): DataSource = UaSwitchingDataSource()
    }
}
